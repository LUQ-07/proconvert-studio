"""Render docs/COMPATIBILITY_MATRIX.md from the capability registry and the latest test results."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from proconvert.core.capabilities import all_routes  # noqa: E402
from proconvert.core.security import FORMAT_LABELS  # noqa: E402


def main() -> None:
    res_path = ROOT / "docs" / "test_results.json"
    res = json.loads(res_path.read_text()) if res_path.exists() else {}
    env = res.get("environment", "not yet recorded")
    routes_ok = res.get("routes_passed", {})
    batch_ok = res.get("batch_routes_passed", False)
    lines = [
        "# Conversion compatibility matrix",
        "",
        "Generated by `tools/gen_matrix.py` from `proconvert/core/capabilities.py` and `docs/test_results.json`.",
        "**Tiers.** *Supported* = text, tables and images map naturally and are covered by automated tests; layout is still rebuilt, not copied. "
        "*Experimental* = structure is reconstructed heuristically; always review the result.",
        "",
        f"**Tested platforms:** {env}. Windows and macOS: engine code is pure Python and platform-neutral, but it has **not** been executed there. "
        "The GUI and installers have **not** been executed on any platform.",
        "",
        "| Route | Tier | Engine | Engine test (this env) | Batch test | Main limitations | Library licenses |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in all_routes():
        ok = routes_ok.get(r.key)
        lines.append(
            f"| {FORMAT_LABELS[r.source]} -> {FORMAT_LABELS[r.target]} | {'Supported' if not r.experimental else 'Experimental'} | "
            f"{r.engine} | {'pass' if ok else ('FAIL' if ok is False else 'not run')} | {'pass' if batch_ok else 'not run'} | "
            f"{'; '.join(r.limitations)} | {r.licensing} |"
        )
    lines += ["", "## Common limitations", "- Fonts, exact page layout, headers/footers, comments, macros and animations are not reproduced.",
              "- Scanned PDFs need OCR (optional; requires a Tesseract install) - otherwise pages are inserted as images.",
              "- Password-protected Office files must be unlocked first; PDFs ask for the password."]
    (ROOT / "docs" / "COMPATIBILITY_MATRIX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/COMPATIBILITY_MATRIX.md")


if __name__ == "__main__":
    main()
