"""Run the whole suite and write docs/test_results.json + docs/TEST_REPORT.md. Reports exactly what ran."""
from __future__ import annotations

import json
import os
import platform
import sys
import time
import unittest
from collections import OrderedDict
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


class Recorder(unittest.TextTestResult):
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self.rows: "OrderedDict[str, tuple[str, str]]" = OrderedDict()

    def addSuccess(self, test):
        super().addSuccess(test); self.rows[test.id()] = ("pass", "")

    def addFailure(self, test, err):
        super().addFailure(test, err); self.rows[test.id()] = ("FAIL", str(err[1])[:300])

    def addError(self, test, err):
        super().addError(test, err); self.rows[test.id()] = ("ERROR", f"{err[0].__name__}: {str(err[1])[:300]}")

    def addSkip(self, test, reason):
        super().addSkip(test, reason); self.rows[test.id()] = ("skipped", reason)

    def addSubTest(self, test, subtest, err):
        super().addSubTest(test, subtest, err)
        if err is not None:
            self.rows[subtest.id()] = ("FAIL", str(err[1])[:300])


def versions() -> dict[str, str]:
    out = {}
    for n in ("pdfplumber", "pdfminer.six", "pypdf", "pypdfium2", "python-docx", "python-pptx", "openpyxl", "reportlab", "Pillow", "lxml", "cryptography", "defusedxml", "pytesseract"):
        try:
            out[n] = metadata.version(n)
        except metadata.PackageNotFoundError:
            out[n] = "not installed"
    return out


def main() -> int:
    for stream in (sys.stdout, sys.stderr):   # Windows consoles may not be UTF-8; never crash while printing a test note
        try:
            stream.reconfigure(errors="replace")
        except (AttributeError, ValueError):
            pass
    suite = unittest.defaultTestLoader.discover(str(ROOT / "tests"), top_level_dir=str(ROOT))
    t0 = time.time()
    runner = unittest.TextTestRunner(resultclass=Recorder, verbosity=0, stream=open(os.devnull, "w", encoding="utf-8"))
    result = runner.run(suite)
    secs = time.time() - t0
    rows = result.rows
    counts = {k: sum(1 for s, _ in rows.values() if s == k) for k in ("pass", "FAIL", "ERROR", "skipped")}
    env = f"{platform.system()} {platform.release()} {platform.machine()}, Python {platform.python_version()} ({os.cpu_count()} CPU(s); the host may be a CI runner or the authoring sandbox)"
    from proconvert import selftest
    st = selftest.run(verbose=False)
    batch_status = next((s for t, (s, _) in rows.items() if t.endswith("test_batch_runs_all_twelve_routes")), "not run")
    data = {"environment": env, "date": time.strftime("%Y-%m-%d"), "seconds": round(secs, 1), "counts": counts, "total": len(rows),
            "libraries": versions(), "routes_passed": {r["route"].replace("->", "->"): r["ok"] for r in st["routes"]},
            "batch_routes_passed": batch_status == "pass"}
    (ROOT / "docs" / "test_results.json").write_text(json.dumps(data, indent=2), encoding="utf-8")

    by_mod: "OrderedDict[str, list]" = OrderedDict()
    for tid, (status, note) in rows.items():
        mod = ".".join(tid.split(".")[:2])
        by_mod.setdefault(mod, []).append((tid.split(".", 2)[2], status, note))
    md = ["# Test report", "", f"Generated by `tools/run_tests.py` on {data['date']}. Environment: **{env}**.", "",
          f"**{counts['pass']} passed, {counts['FAIL']} failed, {counts['ERROR']} errors, {counts['skipped']} skipped** "
          f"({len(rows)} test results, {secs:.0f} s).", "",
          "Library versions used: " + ", ".join(f"{k} {v}" for k, v in data["libraries"].items()) + ".", "",
          "## What was NOT executed in the authoring sandbox (CI runs are reported separately by the workflow)", "",
          "- **The real PySide6 GUI** (PySide6 is not installable offline here). `tests/test_ui_smoke.py` runs UI code against a *fake* Qt: it catches typos and logic errors in our code, not Qt rendering or Qt API misuse.",
          "- **Windows and macOS** (no such machines); **PyInstaller builds, installers, signing, notarization** (tools unavailable).",
          "- **The `.deb` script was exercised only with a dummy payload**; **AppImage** was not built (no appimagetool).",
          "- **Dependency versions required by `requirements/base.txt`** (notably pypdf >= 6.14.1): the suite ran against the versions listed above.",
          "- **`pip-audit`** (offline).", "- Accessibility with a screen reader; right-to-left layout rendering; large-scale performance on typical customer hardware.", ""]
    for mod, items in by_mod.items():
        md.append(f"## {mod}")
        md.append("| Test | Result | Note |\n|---|---|---|")
        for name, status, note in items:
            md.append(f"| `{name}` | {status} | {note.replace('|', '/')[:160]} |")
        md.append("")
    (ROOT / "docs" / "TEST_REPORT.md").write_text("\n".join(md), encoding="utf-8")
    print(json.dumps(counts), f"{secs:.0f}s")
    for tid, (s, note) in rows.items():
        if s in ("FAIL", "ERROR"):
            print(s, tid, note)
    return 0 if counts["FAIL"] == 0 and counts["ERROR"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
